#!/usr/bin/env node

/**
 * Sets up type dependencies:
 * - Installs missing @types/* packages
 * - Creates declaration files for untyped libraries
 * - Generates type stubs for internal modules
 */

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');
const {
  formatError,
  formatSuccess,
  formatInfo,
  formatWarning,
  validatePrerequisites,
  parseArgs
} = require('./error-utils');

function loadAnalysisResults(rootDir) {
  const analysisPath = path.join(rootDir, '.migration-missing-types.json');
  
  if (fs.existsSync(analysisPath)) {
    return JSON.parse(fs.readFileSync(analysisPath, 'utf-8'));
  }
  
  return null;
}

function detectPackageManager(rootDir) {
  if (fs.existsSync(path.join(rootDir, 'pnpm-lock.yaml'))) {
    return 'pnpm';
  } else if (fs.existsSync(path.join(rootDir, 'yarn.lock'))) {
    return 'yarn';
  }
  return 'npm';
}

function getInstallCommand(packageManager, packages, isDev = true) {
  const commands = {
    npm: `npm install ${isDev ? '--save-dev' : ''} ${packages.join(' ')}`,
    yarn: `yarn add ${isDev ? '--dev' : ''} ${packages.join(' ')}`,
    pnpm: `pnpm add ${isDev ? '--save-dev' : ''} ${packages.join(' ')}`
  };
  
  return commands[packageManager];
}

function installTypePackages(rootDir, packages, packageManager) {
  if (packages.length === 0) {
    return { success: true, installed: [], failed: [] };
  }
  
  const typePackages = packages.map(pkg => `@types/${pkg}`);
  const command = getInstallCommand(packageManager, typePackages, true);
  
  console.error(formatInfo(`Installing ${typePackages.length} type packages...`));
  
  try {
    execSync(command, { cwd: rootDir, stdio: 'inherit' });
    return { success: true, installed: typePackages, failed: [] };
  } catch (error) {
    // Try installing one by one to identify failures
    const installed = [];
    const failed = [];
    
    for (const typePkg of typePackages) {
      try {
        const singleCommand = getInstallCommand(packageManager, [typePkg], true);
        execSync(singleCommand, { cwd: rootDir, stdio: 'pipe' });
        installed.push(typePkg);
        console.error(formatSuccess(`Installed ${typePkg}`));
      } catch {
        failed.push(typePkg);
        console.error(formatWarning(`Failed to install ${typePkg}`));
      }
    }
    
    return { success: failed.length === 0, installed, failed };
  }
}

function createDeclarationFile(rootDir, packageName, types = null) {
  const typesDir = path.join(rootDir, 'src', 'types');
  const declarationsDir = path.join(typesDir, 'declarations');
  
  if (!fs.existsSync(declarationsDir)) {
    fs.mkdirSync(declarationsDir, { recursive: true });
  }
  
  const fileName = packageName.replace('@', '').replace('/', '-') + '.d.ts';
  const filePath = path.join(declarationsDir, fileName);
  
  if (fs.existsSync(filePath)) {
    console.error(formatWarning(`Declaration file already exists: ${fileName}`));
    return { created: false, path: filePath };
  }
  
  let content;
  
  if (types && typeof types === 'object') {
    // Generate typed declaration
    const typeDefinitions = Object.entries(types)
      .map(([name, type]) => {
        if (typeof type === 'object') {
          return `  export const ${name}: ${JSON.stringify(type)};`;
        }
        return `  export const ${name}: ${type};`;
      })
      .join('\n');
    
    content = `/**
 * Type declarations for ${packageName}
 * Auto-generated by js-to-ts-migration
 * 
 * TODO: Review and improve type definitions
 */

declare module '${packageName}' {
${typeDefinitions}
}
`;
  } else {
    // Generate basic declaration
    content = `/**
 * Type declarations for ${packageName}
 * Auto-generated by js-to-ts-migration
 * 
 * TODO: Add proper type definitions
 */

declare module '${packageName}' {
  // Add type definitions here
  export function example(): void;
}
`;
  }
  
  fs.writeFileSync(filePath, content);
  return { created: true, path: filePath };
}

function createDeclarationIndex(rootDir) {
  const typesDir = path.join(rootDir, 'src', 'types');
  const declarationsDir = path.join(typesDir, 'declarations');
  
  if (!fs.existsSync(declarationsDir)) {
    fs.mkdirSync(declarationsDir, { recursive: true });
  }
  
  const indexPath = path.join(declarationsDir, 'index.d.ts');
  
  // Find all declaration files
  const files = fs.readdirSync(declarationsDir)
    .filter(f => f.endsWith('.d.ts') && f !== 'index.d.ts');
  
  const content = `/**
 * Type declarations index
 * Auto-generated by js-to-ts-migration
 */

${files.map(f => `/// <reference path="./${f}" />`).join('\n')}
`;
  
  fs.writeFileSync(indexPath, content);
}

function updateTsconfig(rootDir) {
  const tsconfigPath = path.join(rootDir, 'tsconfig.json');
  
  if (!fs.existsSync(tsconfigPath)) {
    console.error(formatWarning('No tsconfig.json found, skipping include update'));
    return false;
  }
  
  try {
    const tsconfig = JSON.parse(fs.readFileSync(tsconfigPath, 'utf-8'));
    
    // Ensure typeRoots includes our declarations
    if (!tsconfig.compilerOptions.typeRoots) {
      tsconfig.compilerOptions.typeRoots = ['./node_modules/@types', './src/types/declarations'];
    } else if (!tsconfig.compilerOptions.typeRoots.includes('./src/types/declarations')) {
      tsconfig.compilerOptions.typeRoots.push('./src/types/declarations');
    }
    
    // Ensure src/types is included
    if (!tsconfig.include) {
      tsconfig.include = ['src/**/*'];
    } else if (!tsconfig.include.some(p => p.includes('src/types'))) {
      // Already covered by src/**/*
    }
    
    fs.writeFileSync(tsconfigPath, JSON.stringify(tsconfig, null, 2));
    console.error(formatSuccess('Updated tsconfig.json with type declarations'));
    return true;
  } catch (error) {
    console.error(formatWarning(`Could not update tsconfig.json: ${error.message}`));
    return false;
  }
}

function generateTypeStubs(rootDir, modules) {
  const stubsDir = path.join(rootDir, 'src', 'types', 'stubs');
  
  if (!fs.existsSync(stubsDir)) {
    fs.mkdirSync(stubsDir, { recursive: true });
  }
  
  const created = [];
  
  for (const moduleName of modules) {
    const stubPath = path.join(stubsDir, `${moduleName}.ts`);
    
    if (fs.existsSync(stubPath)) {
      continue;
    }
    
    const content = `/**
 * Type stub for ${moduleName}
 * Auto-generated by js-to-ts-migration
 * 
 * This is a temporary stub. Replace with actual types.
 */

// TODO: Add proper types
export const ${moduleName} = {
  // Add exports here
};

export type ${moduleName}Type = typeof ${moduleName};
`;
    
    fs.writeFileSync(stubPath, content);
    created.push(moduleName);
  }
  
  return created;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const rootDir = args.positional[0] || process.cwd();
  const verbose = args.options.verbose || args.options.v || false;
  const dryRun = args.options['dry-run'] || false;
  
  console.error('=== Setting Up Type Dependencies ===\n');
  
  // Validate prerequisites
  const errors = validatePrerequisites(rootDir, { packageJson: true });
  if (errors.length > 0) {
    console.error(formatError(new Error(errors.join('\n')), 'Prerequisites'));
    process.exit(1);
  }
  
  // Detect package manager
  const packageManager = detectPackageManager(rootDir);
  console.error(formatInfo(`Detected package manager: ${packageManager}`));
  
  // Load analysis results
  const analysis = loadAnalysisResults(rootDir);
  
  let typesToInstall = [];
  let typesNeedingDeclarations = [];
  
  if (analysis && analysis.missingTypes) {
    typesToInstall = analysis.missingTypes.needsInstall || [];
    typesNeedingDeclarations = analysis.missingTypes.needsDeclaration || [];
  } else {
    console.error(formatWarning('No analysis results found. Run analyze-missing-types.js first.'));
    console.error(formatInfo('Proceeding with basic type setup...'));
  }
  
  // Handle explicit packages from arguments
  if (args.options.install) {
    const explicitPackages = args.options.install.split(',').map(s => s.trim());
    typesToInstall = [...new Set([...typesToInstall, ...explicitPackages])];
  }
  
  if (args.options.declare) {
    const explicitDeclarations = args.options.declare.split(',').map(s => s.trim());
    typesNeedingDeclarations = [...new Set([...typesNeedingDeclarations, ...explicitDeclarations])];
  }
  
  const result = {
    success: true,
    packageManager,
    installed: [],
    declarations: [],
    stubs: [],
    errors: []
  };
  
  // Install @types packages
  if (typesToInstall.length > 0 && !dryRun) {
    console.error(formatInfo(`Installing ${typesToInstall.length} @types packages...`));
    const installResult = installTypePackages(rootDir, typesToInstall, packageManager);
    result.installed = installResult.installed;
    
    if (installResult.failed.length > 0) {
      // Add failed packages to declarations list
      typesNeedingDeclarations = [
        ...typesNeedingDeclarations,
        ...installResult.failed.map(p => p.replace('@types/', ''))
      ];
    }
  } else if (dryRun) {
    console.error(formatInfo(`[DRY RUN] Would install: ${typesToInstall.map(t => `@types/${t}`).join(', ')}`));
    result.installed = typesToInstall.map(t => `@types/${t}`);
  }
  
  // Create declaration files
  if (typesNeedingDeclarations.length > 0) {
    console.error(formatInfo(`Creating ${typesNeedingDeclarations.length} declaration files...`));
    
    for (const pkg of typesNeedingDeclarations) {
      if (!dryRun) {
        const declResult = createDeclarationFile(rootDir, pkg);
        if (declResult.created) {
          result.declarations.push(pkg);
          console.error(formatSuccess(`Created declaration for ${pkg}`));
        }
      } else {
        console.error(formatInfo(`[DRY RUN] Would create declaration for: ${pkg}`));
        result.declarations.push(pkg);
      }
    }
    
    // Create declaration index
    if (!dryRun && result.declarations.length > 0) {
      createDeclarationIndex(rootDir);
    }
  }
  
  // Update tsconfig
  if (!dryRun && (result.declarations.length > 0 || result.installed.length > 0)) {
    updateTsconfig(rootDir);
  }
  
  // Print summary
  console.error('\n=== Summary ===');
  console.error(`Installed @types: ${result.installed.length}`);
  console.error(`Created declarations: ${result.declarations.length}`);
  
  if (result.declarations.length > 0) {
    console.error('\nNext steps:');
    console.error('1. Review generated declaration files in src/types/declarations/');
    console.error('2. Add proper type definitions to declaration files');
    console.error('3. Run npx tsc --noEmit to verify types');
  }
  
  console.log(JSON.stringify(result, null, 2));
}

main();
